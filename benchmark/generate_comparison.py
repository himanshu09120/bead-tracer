"""
benchmark/generate_comparison.py

Reads every *.json result file in benchmark/results/ (written by
evaluate_ours.py and each baseline's own script, all via the shared
common/metrics.py schema) and produces:
  - benchmark/report/comparison_table.md  (markdown table, human-readable)
  - benchmark/report/comparison_table.csv (flat CSV, one row per method)
  - benchmark/plots/*.png                 (bar charts comparing methods)

This script does not run any model or environment itself -- it only reads
already-computed results and renders them. Run it any time after some subset
of the benchmark scripts have been run; it will simply show whatever is
present in benchmark/results/ and note what's missing.
"""

import csv
import glob
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(_HERE, "results")
REPORT_DIR = os.path.join(_HERE, "report")
PLOTS_DIR = os.path.join(_HERE, "plots")

# Display order / labels for known methods. Anything not listed here still
# appears (sorted alphabetically after these), so a partial benchmark run
# still produces a complete table for whatever exists.
METHOD_ORDER = [
    ("ppo_ours", "Our PPO (BeadEnv, contour coverage)"),
    ("classical_greedy", "Classical: greedy nearest-uncovered"),
    ("classical_raster", "Classical: raster sweep"),
    ("sensors_ppo", "Reimpl.: Garrido-Castaneda et al. 2025 (PPO, grid)"),
    ("sensors_a2c", "Reimpl.: Garrido-Castaneda et al. 2025 (A2C, grid)"),
    ("redqn_baseline_dqn", "Reimpl.: Chen et al. 2025 baseline (DQN, grid)"),
    ("rlcpp_mowing_tv1_bundled", "Official code+checkpoint: Jonnarth et al. 2024/2025 (authors' bundled metrics)"),
    ("rlcpp_mowing_tv1_local", "Official code+checkpoint: Jonnarth et al. 2024/2025 (our local run)"),
    ("theile_dqn", "Reimpl.: Theile et al. 2020 IROS (DQN, UAV power-constrained grid)"),
    ("devo_ppo", "Reimpl.: Devo et al. 2022 RA-L (PPO proxy for IMPALA, exploration grid)"),
]


def load_all_results() -> dict:
    results = {}
    for path in glob.glob(os.path.join(RESULTS_DIR, "*.json")):
        method = os.path.splitext(os.path.basename(path))[0]
        with open(path) as f:
            results[method] = json.load(f)
    return results


def write_markdown_table(results: dict, out_path: str):
    ordered_keys = [k for k, _ in METHOD_ORDER if k in results]
    ordered_keys += sorted(k for k in results if k not in dict(METHOD_ORDER))

    lines = [
        "# Benchmark comparison table",
        "",
        "Generated by `benchmark/generate_comparison.py`. Every number below "
        "comes from the corresponding method's own `results/<method>.json`, "
        "computed via the shared `benchmark/common/metrics.py` module -- no "
        "number here is hand-edited.",
        "",
        "| Method | Environment | Mean coverage % (std) | Success rate | "
        "Mean steps | Mean path length | Mean redundancy | n episodes |",
        "|---|---|---|---|---|---|---|---|",
    ]
    label_map = dict(METHOD_ORDER)
    for key in ordered_keys:
        r = results[key]
        s = r["summary"]
        meta = r.get("meta", {})
        label = label_map.get(key, key)
        env = meta.get("environment", "?")
        lines.append(
            f"| {label} | {env} | "
            f"{s['mean_coverage_pct']:.2f}% ({s['std_coverage_pct']:.2f}) | "
            f"{s['success_rate']*100:.1f}% | "
            f"{s['mean_steps']:.1f} | "
            f"{s['mean_path_length']:.1f} | "
            f"{s['mean_redundancy_rate']:.3f} | "
            f"{s['n_episodes']} |"
        )
    lines += [
        "",
        "**Important caveat on 'apples-to-apples':** path length and step "
        "count are in each method's OWN native units (BeadEnv: raster "
        "pixels; grid baselines: grid cells) and are NOT directly comparable "
        "in absolute terms across methods with different environments. "
        "Coverage %, success rate, and redundancy rate ARE dimensionless "
        "and comparable in spirit, but still reflect different underlying "
        "tasks (contour tracing vs. area/grid coverage) -- see the report's "
        "limitations section before drawing strong conclusions from any "
        "single number in this table.",
    ]
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write("\n".join(lines))


def write_csv_table(results: dict, out_path: str):
    fieldnames = ["method", "environment", "mean_coverage_pct", "std_coverage_pct",
                  "success_rate", "mean_steps", "mean_path_length",
                  "mean_redundancy_rate", "n_episodes"]
    with open(out_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for key, r in results.items():
            s = r["summary"]
            meta = r.get("meta", {})
            writer.writerow({
                "method": key,
                "environment": meta.get("environment", "?"),
                "mean_coverage_pct": s["mean_coverage_pct"],
                "std_coverage_pct": s["std_coverage_pct"],
                "success_rate": s["success_rate"],
                "mean_steps": s["mean_steps"],
                "mean_path_length": s["mean_path_length"],
                "mean_redundancy_rate": s["mean_redundancy_rate"],
                "n_episodes": s["n_episodes"],
            })


def _sorted_items(results: dict):
    ordered_keys = [k for k, _ in METHOD_ORDER if k in results]
    ordered_keys += sorted(k for k in results if k not in dict(METHOD_ORDER))
    label_map = dict(METHOD_ORDER)
    return [(k, label_map.get(k, k)) for k in ordered_keys]


def plot_coverage_bar(results: dict, out_path: str):
    items = _sorted_items(results)
    labels = [lbl for _, lbl in items]
    means = [results[k]["summary"]["mean_coverage_pct"] for k, _ in items]
    stds = [results[k]["summary"]["std_coverage_pct"] for k, _ in items]

    fig, ax = plt.subplots(figsize=(10, max(4, 0.6 * len(items))))
    y = np.arange(len(items))
    colors = ["#2E86AB" if k == "ppo_ours" else "#A6A6A6" for k, _ in items]
    ax.barh(y, means, xerr=stds, color=colors, capsize=4)
    ax.set_yticks(y)
    ax.set_yticklabels(labels, fontsize=9)
    ax.invert_yaxis()
    ax.set_xlabel("Mean coverage % (error bars = std across episodes)")
    ax.set_title("Coverage comparison across methods")
    ax.set_xlim(0, 105)
    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


def plot_success_and_redundancy(results: dict, out_path: str):
    items = _sorted_items(results)
    labels = [lbl for _, lbl in items]
    success = [results[k]["summary"]["success_rate"] * 100 for k, _ in items]
    redundancy = [results[k]["summary"]["mean_redundancy_rate"] * 100 for k, _ in items]

    fig, axes = plt.subplots(1, 2, figsize=(14, max(4, 0.6 * len(items))))
    y = np.arange(len(items))
    colors = ["#2E86AB" if k == "ppo_ours" else "#A6A6A6" for k, _ in items]

    axes[0].barh(y, success, color=colors)
    axes[0].set_yticks(y)
    axes[0].set_yticklabels(labels, fontsize=9)
    axes[0].invert_yaxis()
    axes[0].set_xlabel("Success / completion rate (%)")
    axes[0].set_xlim(0, 105)
    axes[0].set_title("Task completion rate")

    axes[1].barh(y, redundancy, color=colors)
    axes[1].set_yticks(y)
    axes[1].set_yticklabels([])
    axes[1].invert_yaxis()
    axes[1].set_xlabel("Mean redundancy rate (%) -- lower is better")
    axes[1].set_xlim(0, 105)
    axes[1].set_title("Redundant / unproductive steps")

    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


def main():
    results = load_all_results()
    if not results:
        print("No results found in benchmark/results/. Run the baseline "
              "scripts and benchmark/evaluate_ours.py first.")
        return

    print(f"Found {len(results)} result file(s): {sorted(results.keys())}")

    os.makedirs(REPORT_DIR, exist_ok=True)
    os.makedirs(PLOTS_DIR, exist_ok=True)

    md_path = os.path.join(REPORT_DIR, "comparison_table.md")
    csv_path = os.path.join(REPORT_DIR, "comparison_table.csv")
    write_markdown_table(results, md_path)
    write_csv_table(results, csv_path)
    print(f"Wrote {md_path}")
    print(f"Wrote {csv_path}")

    coverage_plot = os.path.join(PLOTS_DIR, "coverage_comparison.png")
    success_plot = os.path.join(PLOTS_DIR, "success_redundancy_comparison.png")
    plot_coverage_bar(results, coverage_plot)
    plot_success_and_redundancy(results, success_plot)
    print(f"Wrote {coverage_plot}")
    print(f"Wrote {success_plot}")


if __name__ == "__main__":
    main()
